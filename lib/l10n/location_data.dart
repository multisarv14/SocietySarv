  /// States / union territories for a country, empty when only free text applies.
  static List<String> statesOf(String country) {
    switch (country) {
      case 'India':
        return _indiaStates.keys.toList()..sort();
      case 'United Arab Emirates':
        return _uaeEmirates;
      case 'United States':
        return _usStates;
      case 'United Kingdom':
        return _ukRegions;
      case 'Canada':
        return _canadaProvinces;
      case 'Australia':
        return _australiaStates;
      default:
        return const [];
    }
  }

  /// Cities for a state, empty when the user should simply type one in.
  static List<String> citiesOf(String country, String state) =>
