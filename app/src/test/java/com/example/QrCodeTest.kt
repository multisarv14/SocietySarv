    @Test
    fun `the smallest version that fits is the one chosen`() {
        // The published byte-mode capacities at ECC level M, either side of
        // each boundary: one byte more has to step up a version.
        assertEquals(1, QrCode.encode("a".repeat(14)).version)
        assertEquals(2, QrCode.encode("a".repeat(15)).version)
        assertEquals(2, QrCode.encode("a".repeat(26)).version)
        assertEquals(3, QrCode.encode("a".repeat(27)).version)
        assertEquals(9, QrCode.encode("a".repeat(180)).version)
        // Version 10 is where the character count widens to 16 bits, which is
        // why it holds 213 bytes rather than carrying straight on from 180.
        assertEquals(10, QrCode.encode("a".repeat(181)).version)
        assertEquals(10, QrCode.encode("a".repeat(213)).version)
        assertEquals(11, QrCode.encode("a".repeat(214)).version)
        assertEquals(40, QrCode.encode("a".repeat(2331)).version)
    }

    @Test
    fun `a payload too long for any symbol is refused rather than silently cut`() {
        val error = runCatching { QrCode.encode("a".repeat(2332)) }.exceptionOrNull()

        assertTrue(error is IllegalArgumentException)
    }

    @Test
    fun `multi-byte characters are measured in bytes, not characters`() {
        // A society name in Devanagari is three bytes per character in UTF-8,
        // so eight of them must not be mistaken for eight bytes.
        val marathi = "सोसायटी"

        assertEquals(21, marathi.toByteArray(Charsets.UTF_8).size)
        // 21 bytes plus 6 is 27, one past what a version 2 symbol holds.
        assertEquals(3, QrCode.encode(marathi + "a".repeat(6)).version)
        assertEquals(2, QrCode.encode(marathi + "a".repeat(5)).version)
    }

    @Test
    fun `an empty payload still produces a symbol a scanner can lock onto`() {
        val symbol = QrCode.encode("")

        assertEquals(21, symbol.size)
        // The dark centre of each of the three finder patterns.
        assertTrue(symbol[3, 3])
        assertTrue(symbol[symbol.size - 4, 3])
        assertTrue(symbol[3, symbol.size - 4])
    }

    @Test
    fun `reading past the edge is light, so a quiet zone needs no special case`() {
        val symbol = QrCode.encode("SocietySarv")

        assertTrue(!symbol[-1, 0])
        assertTrue(!symbol[0, -1])
        assertTrue(!symbol[symbol.size, 0])
        assertTrue(!symbol[0, symbol.size])
    }

    /** Fails naming the first module that differs, rather than just "not equal". */
    private fun assertMatches(symbol: QrCode.Symbol, reference: List<String>) {
        assertEquals("symbol size", reference.size, symbol.size)
        for (y in reference.indices) {
            for (x in reference[y].indices) {
                assertEquals("module at ($x, $y)", reference[y][x] == '1', symbol[x, y])
            }
        }
    }
